#!/usr/bin/env python3
"""Turn look artwork into C++ headers the firmware and the PC sim both compile in.

  python tools/make_look.py dial  looks/retro/dial.svg  src/looks/RetroDial.h
  python tools/make_look.py badge assets/brand/cooper-s.png src/looks/local/CooperSBadge.h --width 70

dial   Renders an SVG at 240x240 (resvg), dithers to RGB565 and writes an opaque
       image header. Committed: it contains no trademarked artwork.
badge  Scales a PNG with transparency down to its on-screen size and writes RGB565
       colour + 8-bit alpha. For brand artwork: write it under src/looks/local/,
       which is git-ignored, and never commit it.

Needs:  pip install resvg-py pillow
"""
import argparse
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FONT_DIRS = [str(ROOT / "looks" / "retro" / "fonts")]

# 4x4 Bayer matrix: ordered dithering hides banding in the smooth gradients when
# squeezing 8-bit channels into RGB565.
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def to_rgb565(im: Image.Image, dither: bool) -> list[int]:
    px = im.convert("RGB").load()
    out = []
    for y in range(im.height):
        for x in range(im.width):
            r, g, b = px[x, y]
            if dither:
                t = (BAYER[y & 3][x & 3] - 7.5) / 16.0
                r = min(255, max(0, round(r + t * 8)))
                g = min(255, max(0, round(g + t * 4)))
                b = min(255, max(0, round(b + t * 8)))
            out.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return out


def c_array(name: str, values: list[int], ctype: str, per_line: int, width: int) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:0{width}X}" for v in values[i:i + per_line]) + ",")
    return f"inline constexpr {ctype} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"


def header(guard_note: str, namespace: str, body: str) -> str:
    return (
        "#pragma once\n"
        f"// GENERATED by tools/make_look.py: {guard_note}. Do not edit by hand.\n\n"
        "#include <cstdint>\n\n"
        f"namespace {namespace} {{\n\n{body}\n}}  // namespace {namespace}\n"
    )


def cmd_dial(args):
    import resvg_py

    png = resvg_py.svg_to_bytes(
        svg_path=str(args.src), width=240, height=240,
        skip_system_fonts=True, font_dirs=FONT_DIRS,
    )
    tmp = ROOT / "out" / "dial_render.png"
    tmp.parent.mkdir(exist_ok=True)
    tmp.write_bytes(bytes(png))
    im = Image.open(tmp).convert("RGB")
    assert im.size == (240, 240), im.size

    body = (
        "inline constexpr int kDialWidth = 240;\n"
        "inline constexpr int kDialHeight = 240;\n\n"
        "// RGB565, row-major, opaque.\n"
        + c_array("kDialRgb565", to_rgb565(im, dither=True), "uint16_t", 16, 4)
    )
    args.dst.parent.mkdir(parents=True, exist_ok=True)
    args.dst.write_text(header(f"from {args.src.name}", "looks::retro", body))
    print(f"wrote {args.dst} ({args.dst.stat().st_size // 1024} KB); preview: {tmp}")


def cmd_badge(args):
    src = Image.open(args.src).convert("RGBA")
    height = max(1, round(src.height * args.width / src.width))
    im = src.resize((args.width, height), Image.LANCZOS)

    # Straight (non-premultiplied) colour: resize bled transparent-black into the
    # edges, so take colour from a version resized with alpha-weighting.
    pre = Image.new("RGBA", src.size)
    sp, pp = src.load(), pre.load()
    for y in range(src.height):
        for x in range(src.width):
            r, g, b, a = sp[x, y]
            pp[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
    small = pre.resize((args.width, height), Image.LANCZOS)
    smp, ip = small.load(), im.load()
    for y in range(height):
        for x in range(args.width):
            r, g, b, a = smp[x, y]
            if a:
                ip[x, y] = (min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a), a)

    rgb = Image.new("RGB", im.size)
    rgb.putdata([p[:3] for p in im.getdata()])
    alpha = [p[3] for p in im.getdata()]

    body = (
        f"inline constexpr int kWidth = {args.width};\n"
        f"inline constexpr int kHeight = {height};\n\n"
        + c_array("kRgb565", to_rgb565(rgb, dither=False), "uint16_t", 16, 4)
        + "\n"
        + c_array("kAlpha", alpha, "uint8_t", 24, 2)
    )
    args.dst.parent.mkdir(parents=True, exist_ok=True)
    args.dst.write_text(header(f"from {args.src.name} (brand artwork: keep local)", "looks::badge", body))
    print(f"wrote {args.dst} ({args.width}x{height})")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    dial = sub.add_parser("dial")
    dial.add_argument("src", type=Path)
    dial.add_argument("dst", type=Path)
    dial.set_defaults(fn=cmd_dial)
    badge = sub.add_parser("badge")
    badge.add_argument("src", type=Path)
    badge.add_argument("dst", type=Path)
    badge.add_argument("--width", type=int, default=70, help="on-screen width in pixels")
    badge.set_defaults(fn=cmd_badge)
    args = parser.parse_args()
    args.fn(args)


if __name__ == "__main__":
    sys.exit(main())

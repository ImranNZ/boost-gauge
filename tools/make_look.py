#!/usr/bin/env python3
"""Turn look artwork into C++ headers the firmware and the PC sim both compile in.

  python tools/make_look.py retro
  python tools/make_look.py modern
  python tools/make_look.py badge assets/brand/cooper-s.png src/looks/local/Badge.h --width 70
  python tools/make_look.py badge assets/brand/cooper-s-light.png src/looks/local/BadgeLight.h --namespace badge_light

retro  Builds the Retro 60s dial from looks/retro/spec.json + dial.svg.in: fills the
       graduations, numerals and red band from the spec, renders the SVG at every resolution
       in the s3 and all display profiles (resvg), and dithers each picture to RGB565.
       Writes RetroDial.h, all/RetroDial.h and RetroSpec.h. Use --profile for just one profile.
       The spec is the single source of truth: the picture and the code cannot drift.
modern The same pipeline for the Modern Mini dial (looks/modern/): chrome ring, black
       face, coloured bands. Writes ModernDial.h, all/ModernDial.h and ModernSpec.h.
badge  Scales a PNG with transparency to its on-screen size at every resolution in the
       s3 and all display profiles and writes RGB565 colour + 8-bit alpha faces, one per
       resolution, selected at build time by the same FONT_PROFILE_* flag as the fonts
       (the looks draw the badge through Picture). Use --profile for just one profile.
       For brand artwork: write it under src/looks/local/, which is git-ignored, and
       never commit it.

Needs:  pip install resvg-py pillow
"""
import argparse
import json
import math
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RETRO = ROOT / "looks" / "retro"
MODERN = ROOT / "looks" / "modern"
OUT = ROOT / "out"

# 4x4 Bayer matrix: ordered dithering hides banding in the smooth gradients when
# squeezing 8-bit channels into RGB565.
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


# ------------------------------------------------------------------ C++ output --

def to_rgb565(im: Image.Image, dither: bool) -> list[int]:
    px = im.convert("RGB").load()
    out = []
    for y in range(im.height):
        for x in range(im.width):
            r, g, b = px[x, y]
            if dither:
                t = (BAYER[y & 3][x & 3] - 7.5) / 16.0
                r = min(255, max(0, round(r + t * 8)))
                g = min(255, max(0, round(g + t * 4)))
                b = min(255, max(0, round(b + t * 8)))
            out.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return out


def c_array(name: str, values: list[int], ctype: str, per_line: int, width: int) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:0{width}X}" for v in values[i:i + per_line]) + ",")
    return f"inline constexpr {ctype} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"


def header(note: str, namespace: str, body: str, image: bool = False) -> str:
    image_include = '#include "render/ImageView.h"\n\n' if image else ""
    return (
        "#pragma once\n"
        f"// GENERATED by tools/make_look.py: {note}. Do not edit by hand.\n\n"
        "#include <cstdint>\n\n"
        f"{image_include}"
        f"namespace {namespace} {{\n\n{body}\n}}  // namespace {namespace}\n"
    )


def fmt(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def cfloat(v: float) -> str:
    return f"{float(v)}f" if float(v) != int(v) else f"{int(v)}.0f"


# --------------------------------------------------------------- dial geometry --

class Scale:
    """Pressure -> screen angle, exactly as the firmware's GaugeScale computes it."""

    def __init__(self, spec: dict):
        s = spec["scale"]
        self.min, self.max = s["minPsi"], s["maxPsi"]
        self.start, self.sweep = s["startDeg"], s["sweepDeg"]

    def angle(self, psi: float) -> float:
        return self.start + (psi - self.min) / (self.max - self.min) * self.sweep

    def point(self, radius: float, psi: float, centre: float = 120.0) -> tuple[float, float]:
        a = math.radians(self.angle(psi))
        return centre + radius * math.cos(a), centre + radius * math.sin(a)


def steps(lo: float, hi: float, step: float) -> list[float]:
    count = round((hi - lo) / step)
    return [lo + i * step for i in range(count + 1)]


def tick_path(scale: Scale, psis, outer: float, inner: float) -> str:
    parts = []
    for p in psis:
        x1, y1 = scale.point(outer, p)
        x2, y2 = scale.point(inner, p)
        parts.append(f"M{fmt(x1)} {fmt(y1)}L{fmt(x2)} {fmt(y2)}")
    return "".join(parts)


def arc_path(scale: Scale, radius: float, p0: float, p1: float) -> str:
    x0, y0 = scale.point(radius, p0)
    x1, y1 = scale.point(radius, p1)
    large = 1 if (scale.angle(p1) - scale.angle(p0)) > 180 else 0
    return f"M{fmt(x0)} {fmt(y0)}A{radius} {radius} 0 {large} 1 {fmt(x1)} {fmt(y1)}"


def build_retro_svg(spec: dict) -> str:
    s, d = spec["scale"], spec["dial"]
    scale = Scale(spec)
    majors = steps(s["minPsi"], s["maxPsi"], s["majorStepPsi"])
    major_set = set(majors)
    minors = [p for p in steps(s["minPsi"], s["maxPsi"], s["minorStepPsi"]) if p not in major_set]

    numerals = []
    for p in majors:
        x, y = scale.point(d["numeralRadius"], p)
        fill = ' fill="#a11d14"' if p >= s["redFromPsi"] else ""
        numerals.append(f'<text x="{fmt(x)}" y="{fmt(y)}"{fill}>{int(p)}</text>')

    svg = (RETRO / "dial.svg.in").read_text(encoding="utf-8")
    return (
        svg.replace("@MAJOR_TICKS@", tick_path(scale, majors, d["tickOuterRadius"], d["majorTickInnerRadius"]))
        .replace("@MINOR_TICKS@", tick_path(scale, minors, d["tickOuterRadius"], d["minorTickInnerRadius"]))
        .replace("@RED_BAND@", arc_path(scale, d["redBandRadius"], s["redFromPsi"], s["maxPsi"]))
        .replace("@NUMERALS@", "\n    ".join(numerals))
    )


def numeral_color(spec: dict, psi: float) -> str:
    """The colour of the last numeralColors entry that starts at or below `psi`."""
    chosen = spec["numeralColors"][0]["color"]
    for entry in spec["numeralColors"]:
        if psi >= entry["fromPsi"]:
            chosen = entry["color"]
    return chosen


def build_modern_svg(spec: dict) -> str:
    s, d = spec["scale"], spec["dial"]
    scale = Scale(spec)
    majors = steps(s["minPsi"], s["maxPsi"], s["majorStepPsi"])
    major_set = set(majors)
    minors = [p for p in steps(s["minPsi"], s["maxPsi"], s["minorStepPsi"]) if p not in major_set]

    numerals = []
    for p in majors:
        x, y = scale.point(d["numeralRadius"], p)
        numerals.append(f'<text x="{fmt(x)}" y="{fmt(y)}" fill="{numeral_color(spec, p)}">{int(p)}</text>')

    svg = (MODERN / "dial.svg.in").read_text(encoding="utf-8")
    return (
        svg.replace("@MAJOR_TICKS@", tick_path(scale, majors, d["tickOuterRadius"], d["majorTickInnerRadius"]))
        .replace("@MINOR_TICKS@", tick_path(scale, minors, d["tickOuterRadius"], d["minorTickInnerRadius"]))
        .replace("@AMBER_BAND@", arc_path(scale, d["bandRadius"], s["amberFromPsi"], s["redFromPsi"]))
        .replace("@RED_BAND@", arc_path(scale, d["bandRadius"], s["redFromPsi"], s["maxPsi"]))
        .replace("@NUMERALS@", "\n    ".join(numerals))
    )


# ------------------------------------------------------------------- commands --

def render_svg(svg_text: str, look_dir: Path, size: int) -> Image.Image:
    import resvg_py

    OUT.mkdir(exist_ok=True)
    svg_path = OUT / "dial.svg"
    svg_path.write_text(svg_text, encoding="utf-8")
    png = resvg_py.svg_to_bytes(
        svg_path=str(svg_path), width=size, height=size,
        skip_system_fonts=True, font_dirs=[str(look_dir / "fonts")],
    )
    (OUT / "dial_render.png").write_bytes(bytes(png))
    im = Image.open(OUT / "dial_render.png").convert("RGB")
    assert im.size == (size, size), im.size
    return im


# name -> (folder, class-name prefix for the headers, SVG builder)
DIAL_LOOKS = {
    "retro": (RETRO, "Retro", build_retro_svg),
    "modern": (MODERN, "Modern", build_modern_svg),
}


def cmd_dial(name: str, profile: str | None):
    look_dir, prefix, build_svg = DIAL_LOOKS[name]
    spec = json.loads((look_dir / "spec.json").read_text(encoding="utf-8"))
    profiles = json.loads((ROOT / "tools" / "fonts.json").read_text(encoding="utf-8"))["profiles"]
    selected = ["s3", "all"] if profile is None else [profile]

    for current in selected:
        if current not in profiles:
            sys.exit(f"fonts.json: no profile '{current}'")
        arrays, faces = [], []
        for index, resolution in enumerate(profiles[current]):
            size = round(240 * resolution)
            im = render_svg(build_svg(spec), look_dir, size)
            array_name = f"kDialRgb565{index}"
            arrays.append(c_array(array_name, to_rgb565(im, dither=True), "uint16_t", 16, 4))
            faces.append(f"    {{{size}, {size}, {array_name}, nullptr, {cfloat(resolution)}}},")
        dial_body = (
            "// RGB565, row-major, opaque; one picture per display resolution.\n\n"
            + "\n".join(arrays)
            + "\ninline constexpr gauge::ImageView kDialFaces[] = {\n"
            + "\n".join(faces)
            + "\n};\n"
            + f"inline constexpr int kDialFaceCount = {len(faces)};\n"
        )
        dial_h = ROOT / "src" / "looks" / name
        if current != "s3":
            dial_h /= current
        dial_h /= f"{prefix}Dial.h"
        dial_h.parent.mkdir(parents=True, exist_ok=True)
        dial_h.write_text(header(f"from looks/{name}/dial.svg.in + spec.json, profile {current}",
                                 f"looks::{name}", dial_body, image=True), newline="\n")
        print(f"wrote {dial_h.relative_to(ROOT)} ({dial_h.stat().st_size // 1024} KB, "
              f"{len(faces)} faces)")

    s, p = spec["scale"], spec["pointer"]
    spec_body = (
        f"inline constexpr float kMinPsi = {cfloat(s['minPsi'])};\n"
        f"inline constexpr float kMaxPsi = {cfloat(s['maxPsi'])};\n"
        f"inline constexpr float kStartDeg = {cfloat(s['startDeg'])};\n"
        f"inline constexpr float kSweepDeg = {cfloat(s['sweepDeg'])};\n"
        f"inline constexpr float kNeedleLength = {cfloat(p['needleLength'])};\n"
        f"inline constexpr float kTailLength = {cfloat(p['tailLength'])};\n"
        f"inline constexpr float kFlagInnerRadius = {cfloat(p['flagInnerRadius'])};\n"
        f"inline constexpr float kFlagOuterRadius = {cfloat(p['flagOuterRadius'])};\n"
        f"inline constexpr int kHubRadius = {int(p['hubRadius'])};\n"
    )
    spec_h = ROOT / "src" / "looks" / name / f"{prefix}Spec.h"
    spec_h.write_text(header(f"from looks/{name}/spec.json", f"looks::{name}", spec_body), newline="\n")
    print(f"wrote {spec_h.relative_to(ROOT)}; preview: out/dial_render.png")


def badge_face(pre: Image.Image, width: int) -> tuple[Image.Image, list[int], int]:
    """One badge face: premultiplied source resized to `width` design pixels."""
    height = max(1, round(pre.height * width / pre.width))
    small = pre.resize((width, height), Image.LANCZOS)
    smp = small.load()
    colour = Image.new("RGB", small.size)
    cp = colour.load()
    alpha = []
    for y in range(height):
        for x in range(width):
            r, g, b, a = smp[x, y]
            alpha.append(a)
            cp[x, y] = (min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)) if a else (0, 0, 0)
    return colour, alpha, height


def cmd_badge(args):
    src = Image.open(args.src).convert("RGBA")
    height = max(1, round(src.height * args.width / src.width))

    # Resize with alpha-weighted colour so transparent edges do not bleed black in.
    pre = Image.new("RGBA", src.size)
    sp, pp = src.load(), pre.load()
    for y in range(src.height):
        for x in range(src.width):
            r, g, b, a = sp[x, y]
            pp[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)

    profiles = json.loads((ROOT / "tools" / "fonts.json").read_text(encoding="utf-8"))["profiles"]
    selected = ["s3", "all"] if args.profile is None else [args.profile]
    for current in selected:
        if current not in profiles:
            sys.exit(f"fonts.json: no profile '{current}'")

    # One branch per profile, picked by the same FONT_PROFILE_* flag as the fonts; with the
    # default pair the s3 branch is the #else fallback so firmware without a flag compiles.
    order = [p for p in ("p4-720", "all", "s3") if p in selected]
    branches = []
    for current in order:
        arrays, faces = [], []
        for index, resolution in enumerate(profiles[current]):
            width = round(args.width * resolution)
            colour, alpha, face_height = badge_face(pre, width)
            arrays.append(c_array(f"kRgb565{index}", to_rgb565(colour, dither=False), "uint16_t", 16, 4))
            arrays.append(c_array(f"kAlpha{index}", alpha, "uint8_t", 24, 2))
            faces.append(f"    {{{width}, {face_height}, kRgb565{index}, kAlpha{index}, {cfloat(resolution)}}},")
        branches.append((current, "\n".join(arrays)
                         + "\ninline constexpr gauge::ImageView kFaces[] = {\n"
                         + "\n".join(faces)
                         + "\n};\n"
                         + f"inline constexpr int kFaceCount = {len(faces)};\n"))

    body = (f"inline constexpr int kWidth = {args.width};\n"
            f"inline constexpr int kHeight = {height};\n\n")
    guarded = [b for b in branches if b[0] != "s3"]
    plain = [b for b in branches if b[0] == "s3"] or branches[-1:]
    for i, (current, code) in enumerate(guarded):
        macro = f"FONT_PROFILE_{current.upper().replace('-', '_')}"
        body += ("#if" if i == 0 else "#elif") + f" defined({macro})\n" + code
    body += ("#else\n" if guarded else "") + plain[0][1]
    body += "#endif\n" if guarded else ""

    args.dst.parent.mkdir(parents=True, exist_ok=True)
    args.dst.write_text(header(f"from {args.src.name} (brand artwork: keep local)", f"looks::{args.namespace}", body, image=True))
    print(f"wrote {args.dst} ({args.width}x{height} design, profiles: {', '.join(order)})")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    for look in DIAL_LOOKS:
        dial = sub.add_parser(look)
        dial.add_argument("--profile", help="display profile to build (default: s3 and all)")
        dial.set_defaults(fn=lambda args, look=look: cmd_dial(look, args.profile))
    badge = sub.add_parser("badge")
    badge.add_argument("src", type=Path)
    badge.add_argument("dst", type=Path)
    badge.add_argument("--width", type=int, default=70, help="on-screen width in pixels")
    badge.add_argument("--namespace", default="badge",
                       help="C++ namespace under looks:: (the light variant uses badge_light so both can be included)")
    badge.add_argument("--profile", help="display profile to build (default: s3 and all)")
    badge.set_defaults(fn=cmd_badge)
    args = parser.parse_args()
    args.fn(args)


if __name__ == "__main__":
    sys.exit(main())

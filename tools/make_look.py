#!/usr/bin/env python3
"""Turn look artwork into C++ headers the firmware and the PC sim both compile in.

  python tools/make_look.py retro
  python tools/make_look.py badge assets/brand/cooper-s.png src/looks/local/CooperSBadge.h --width 70

retro  Builds the Retro 60s dial from looks/retro/spec.json + dial.svg.in: fills the
       graduations, numerals and red band from the spec, renders the SVG at 240x240
       (resvg), dithers to RGB565, and writes two committed headers:
         src/looks/RetroDial.h   the picture
         src/looks/RetroSpec.h   the geometry the C++ draws with (needle length, scale...)
       The spec is the single source of truth: the picture and the code cannot drift.
badge  Scales a PNG with transparency to its on-screen size and writes RGB565 colour
       + 8-bit alpha. For brand artwork: write it under src/looks/local/, which is
       git-ignored, and never commit it.

Needs:  pip install resvg-py pillow
"""
import argparse
import json
import math
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RETRO = ROOT / "looks" / "retro"
OUT = ROOT / "out"

# 4x4 Bayer matrix: ordered dithering hides banding in the smooth gradients when
# squeezing 8-bit channels into RGB565.
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


# ------------------------------------------------------------------ C++ output --

def to_rgb565(im: Image.Image, dither: bool) -> list[int]:
    px = im.convert("RGB").load()
    out = []
    for y in range(im.height):
        for x in range(im.width):
            r, g, b = px[x, y]
            if dither:
                t = (BAYER[y & 3][x & 3] - 7.5) / 16.0
                r = min(255, max(0, round(r + t * 8)))
                g = min(255, max(0, round(g + t * 4)))
                b = min(255, max(0, round(b + t * 8)))
            out.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return out


def c_array(name: str, values: list[int], ctype: str, per_line: int, width: int) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"0x{v:0{width}X}" for v in values[i:i + per_line]) + ",")
    return f"inline constexpr {ctype} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"


def header(note: str, namespace: str, body: str) -> str:
    return (
        "#pragma once\n"
        f"// GENERATED by tools/make_look.py: {note}. Do not edit by hand.\n\n"
        "#include <cstdint>\n\n"
        f"namespace {namespace} {{\n\n{body}\n}}  // namespace {namespace}\n"
    )


def fmt(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def cfloat(v: float) -> str:
    return f"{float(v)}f" if float(v) != int(v) else f"{int(v)}.0f"


# --------------------------------------------------------------- dial geometry --

class Scale:
    """Pressure -> screen angle, exactly as the firmware's GaugeScale computes it."""

    def __init__(self, spec: dict):
        s = spec["scale"]
        self.min, self.max = s["minPsi"], s["maxPsi"]
        self.start, self.sweep = s["startDeg"], s["sweepDeg"]

    def angle(self, psi: float) -> float:
        return self.start + (psi - self.min) / (self.max - self.min) * self.sweep

    def point(self, radius: float, psi: float, centre: float = 120.0) -> tuple[float, float]:
        a = math.radians(self.angle(psi))
        return centre + radius * math.cos(a), centre + radius * math.sin(a)


def steps(lo: float, hi: float, step: float) -> list[float]:
    count = round((hi - lo) / step)
    return [lo + i * step for i in range(count + 1)]


def tick_path(scale: Scale, psis, outer: float, inner: float) -> str:
    parts = []
    for p in psis:
        x1, y1 = scale.point(outer, p)
        x2, y2 = scale.point(inner, p)
        parts.append(f"M{fmt(x1)} {fmt(y1)}L{fmt(x2)} {fmt(y2)}")
    return "".join(parts)


def arc_path(scale: Scale, radius: float, p0: float, p1: float) -> str:
    x0, y0 = scale.point(radius, p0)
    x1, y1 = scale.point(radius, p1)
    large = 1 if (scale.angle(p1) - scale.angle(p0)) > 180 else 0
    return f"M{fmt(x0)} {fmt(y0)}A{radius} {radius} 0 {large} 1 {fmt(x1)} {fmt(y1)}"


def build_retro_svg(spec: dict) -> str:
    s, d = spec["scale"], spec["dial"]
    scale = Scale(spec)
    majors = steps(s["minPsi"], s["maxPsi"], s["majorStepPsi"])
    major_set = set(majors)
    minors = [p for p in steps(s["minPsi"], s["maxPsi"], s["minorStepPsi"]) if p not in major_set]

    numerals = []
    for p in majors:
        x, y = scale.point(d["numeralRadius"], p)
        fill = ' fill="#a11d14"' if p >= s["redFromPsi"] else ""
        numerals.append(f'<text x="{fmt(x)}" y="{fmt(y)}"{fill}>{int(p)}</text>')

    svg = (RETRO / "dial.svg.in").read_text(encoding="utf-8")
    return (
        svg.replace("@MAJOR_TICKS@", tick_path(scale, majors, d["tickOuterRadius"], d["majorTickInnerRadius"]))
        .replace("@MINOR_TICKS@", tick_path(scale, minors, d["tickOuterRadius"], d["minorTickInnerRadius"]))
        .replace("@RED_BAND@", arc_path(scale, d["redBandRadius"], s["redFromPsi"], s["maxPsi"]))
        .replace("@NUMERALS@", "\n    ".join(numerals))
    )


# ------------------------------------------------------------------- commands --

def render_svg(svg_text: str) -> Image.Image:
    import resvg_py

    OUT.mkdir(exist_ok=True)
    svg_path = OUT / "dial.svg"
    svg_path.write_text(svg_text, encoding="utf-8")
    png = resvg_py.svg_to_bytes(
        svg_path=str(svg_path), width=240, height=240,
        skip_system_fonts=True, font_dirs=[str(RETRO / "fonts")],
    )
    (OUT / "dial_render.png").write_bytes(bytes(png))
    im = Image.open(OUT / "dial_render.png").convert("RGB")
    assert im.size == (240, 240), im.size
    return im


def cmd_retro(_args):
    spec = json.loads((RETRO / "spec.json").read_text(encoding="utf-8"))
    im = render_svg(build_retro_svg(spec))

    dial_body = (
        "inline constexpr int kDialWidth = 240;\n"
        "inline constexpr int kDialHeight = 240;\n\n"
        "// RGB565, row-major, opaque.\n"
        + c_array("kDialRgb565", to_rgb565(im, dither=True), "uint16_t", 16, 4)
    )
    dial_h = ROOT / "src" / "looks" / "RetroDial.h"
    dial_h.parent.mkdir(parents=True, exist_ok=True)
    dial_h.write_text(header("from looks/retro/dial.svg.in + spec.json", "looks::retro", dial_body))

    s, p = spec["scale"], spec["pointer"]
    spec_body = (
        f"inline constexpr float kMinPsi = {cfloat(s['minPsi'])};\n"
        f"inline constexpr float kMaxPsi = {cfloat(s['maxPsi'])};\n"
        f"inline constexpr float kStartDeg = {cfloat(s['startDeg'])};\n"
        f"inline constexpr float kSweepDeg = {cfloat(s['sweepDeg'])};\n"
        f"inline constexpr float kNeedleLength = {cfloat(p['needleLength'])};\n"
        f"inline constexpr float kTailLength = {cfloat(p['tailLength'])};\n"
        f"inline constexpr float kFlagInnerRadius = {cfloat(p['flagInnerRadius'])};\n"
        f"inline constexpr float kFlagOuterRadius = {cfloat(p['flagOuterRadius'])};\n"
        f"inline constexpr int kHubRadius = {int(p['hubRadius'])};\n"
    )
    spec_h = ROOT / "src" / "looks" / "RetroSpec.h"
    spec_h.write_text(header("from looks/retro/spec.json", "looks::retro", spec_body))
    print(f"wrote {dial_h.name} ({dial_h.stat().st_size // 1024} KB) and {spec_h.name}; "
          f"preview: out/dial_render.png")


def cmd_badge(args):
    src = Image.open(args.src).convert("RGBA")
    height = max(1, round(src.height * args.width / src.width))

    # Resize with alpha-weighted colour so transparent edges do not bleed black in.
    pre = Image.new("RGBA", src.size)
    sp, pp = src.load(), pre.load()
    for y in range(src.height):
        for x in range(src.width):
            r, g, b, a = sp[x, y]
            pp[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
    small = pre.resize((args.width, height), Image.LANCZOS)
    smp = small.load()
    colour = Image.new("RGB", small.size)
    cp = colour.load()
    alpha = []
    for y in range(height):
        for x in range(args.width):
            r, g, b, a = smp[x, y]
            alpha.append(a)
            cp[x, y] = (min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a)) if a else (0, 0, 0)

    body = (
        f"inline constexpr int kWidth = {args.width};\n"
        f"inline constexpr int kHeight = {height};\n\n"
        + c_array("kRgb565", to_rgb565(colour, dither=False), "uint16_t", 16, 4)
        + "\n"
        + c_array("kAlpha", alpha, "uint8_t", 24, 2)
    )
    args.dst.parent.mkdir(parents=True, exist_ok=True)
    args.dst.write_text(header(f"from {args.src.name} (brand artwork: keep local)", "looks::badge", body))
    print(f"wrote {args.dst} ({args.width}x{height})")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("retro").set_defaults(fn=cmd_retro)
    badge = sub.add_parser("badge")
    badge.add_argument("src", type=Path)
    badge.add_argument("dst", type=Path)
    badge.add_argument("--width", type=int, default=70, help="on-screen width in pixels")
    badge.set_defaults(fn=cmd_badge)
    args = parser.parse_args()
    args.fn(args)


if __name__ == "__main__":
    sys.exit(main())

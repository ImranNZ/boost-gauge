#!/usr/bin/env python3
"""Turn TrueType fonts into C++ glyph tables the firmware and the PC sim both compile in.

  python tools/make_font.py            # every font in tools/fonts.json
  python tools/make_font.py OutfitLight62

Each font becomes src/looks/fonts/<name>.h: one 8-bit coverage bitmap per glyph
(anti-aliased by FreeType), plus the metrics to lay them out (see lib/core/src/render/Font.h).
Every font is rendered at each size in "scales" (see tools/fonts.json): 1 is the size the looks
are designed at, the others suit the bigger screens, so text stays sharp instead of being
stretched. The headers are committed; never edit them by hand, change tools/fonts.json and
re-run. Only the characters listed are included, which keeps flash use small.

Needs:  pip install "pillow>=10.1"   (fractional font sizes)
"""
import argparse
import json
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "looks" / "fonts"


def load_font(spec: dict, scale: float) -> ImageFont.FreeTypeFont:
    font = ImageFont.truetype(str(ROOT / spec["file"]), spec["size"] * scale)
    if "wght" in spec:
        font.set_variation_by_axes([spec["wght"]])
    return font


def render_glyph(font, ch: str, skew_deg: float):
    """(coverage image, x offset, y offset from the baseline, advance) for one character.

    Drawn on a roomy canvas with the pen at a known spot, optionally sheared about the
    baseline, then cropped to the pixels that were actually inked.
    """
    advance = round(font.getlength(ch))
    size = math.ceil(font.size)
    pad_x, pad_y = size, size * 2
    canvas = Image.new("L", (size * 4, size * 3), 0)
    ImageDraw.Draw(canvas).text((pad_x, pad_y), ch, font=font, fill=255, anchor="ls")

    if skew_deg:
        shear = math.tan(math.radians(skew_deg))
        # Rows above the baseline shift right in proportion to their height above it.
        canvas = canvas.transform(canvas.size, Image.AFFINE, (1, shear, -shear * pad_y, 0, 1, 0),
                                  Image.BICUBIC)

    box = canvas.getbbox()
    if box is None:  # a space: nothing inked
        return Image.new("L", (0, 0)), 0, 0, advance
    return canvas.crop(box), box[0] - pad_x, box[1] - pad_y, advance


def build_face(spec: dict, scale: float):
    """(glyph rows, coverage bytes, ascent) for the font rendered at `scale` times its size."""
    font = load_font(spec, scale)
    skew = spec.get("skew", 0)
    glyphs, alpha = [], bytearray()
    ascent = 0
    for ch in spec["chars"]:
        image, x_off, y_off, advance = render_glyph(font, ch, skew)
        if ch in "H0":
            ascent = max(ascent, -y_off)
        if not (-128 <= x_off <= 127 and -128 <= y_off <= 127 and 0 <= advance <= 255
                and image.width <= 255 and image.height <= 255):
            sys.exit(f"{spec['name']} at {scale}x: '{ch}' metrics do not fit the glyph table")
        glyphs.append((ch, image.width, image.height, x_off, y_off, advance, len(alpha)))
        alpha.extend(image.tobytes())
    return glyphs, alpha, ascent


def cfloat(value: float) -> str:
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return text + (".0f" if "." not in text else "f")


def build(spec: dict, scales: list[float]) -> str:
    name = spec["name"]
    skew = spec.get("skew", 0)
    body, faces, total = [], [], 0
    for index, scale in enumerate(scales):
        glyphs, alpha, ascent = build_face(spec, scale)
        total += len(alpha)
        rows = []
        for ch, w, h, xo, yo, adv, offset in glyphs:
            literal = "'\\''" if ch == "'" else ("'\\\\'" if ch == "\\" else f"'{ch}'")
            rows.append(f"    {{{literal}, {w}, {h}, {xo}, {yo}, {adv}, {offset}}},")
        data = []
        for i in range(0, len(alpha), 24):
            data.append("    " + ", ".join(f"{b}" for b in alpha[i:i + 24]) + ",")
        body += [
            f"// {cfloat(scale)[:-1]}x: {len(alpha)} bytes of coverage.",
            f"inline constexpr gauge::Glyph k{name}Glyphs{index}[] = {{",
            *rows,
            "};",
            "",
            f"inline constexpr uint8_t k{name}Alpha{index}[] = {{",
            *data,
            "};",
            "",
        ]
        faces.append(f"    {{k{name}Glyphs{index}, {len(glyphs)}, k{name}Alpha{index}, {ascent}, "
                     f"{cfloat(scale)}}},")

    return "\n".join([
        "// GENERATED by tools/make_font.py from tools/fonts.json. Do not edit.",
        f"// {spec['file']}, {spec['size']} px"
        + (f", weight {spec['wght']}" if "wght" in spec else "")
        + (f", skewed {skew} deg" if skew else "")
        + f", {len(spec['chars'])} characters, at {len(scales)} sizes, {total} bytes of coverage.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        '#include "render/Font.h"',
        "",
        "namespace looks::fonts {",
        "",
        *body,
        f"inline constexpr gauge::FontFace k{name}Faces[] = {{",
        *faces,
        "};",
        "",
        f"inline gauge::Font {name[0].lower()}{name[1:]}() {{",
        f"  return gauge::Font(k{name}Faces, {len(scales)});",
        "}",
        "",
        "}  // namespace looks::fonts",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("names", nargs="*", help="fonts to build (default: all)")
    args = parser.parse_args()

    config = json.loads((ROOT / "tools" / "fonts.json").read_text())
    scales = config.get("scales", [1.0])
    if scales != sorted(scales) or scales[0] != 1.0:
        sys.exit("fonts.json: scales must start at 1 and increase")
    wanted = [s for s in config["fonts"] if not args.names or s["name"] in args.names]
    if not wanted:
        sys.exit("no such font in tools/fonts.json")

    OUT.mkdir(parents=True, exist_ok=True)
    for spec in wanted:
        text = build(spec, scales)
        path = OUT / f"{spec['name']}.h"
        path.write_text(text, newline="\n")
        print(f"wrote {path.relative_to(ROOT)} ({len(text) // 1024} KB source)")


if __name__ == "__main__":
    main()
